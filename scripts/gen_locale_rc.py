"""Generate an embeddable Simplified-Chinese resource block from the upstream
locale script.

The upstream project ships localizations as separate DLLs built from
``locale/<lang>/Notepad4.rc``. To support a single-file distribution we compile
the same resources into Notepad4.exe as a second language block.

The locale script also contains binary resources (icons, bitmaps, the
application manifest) and the Visual Studio designer sections. Those must be
dropped: they already exist in the main resource script and would collide.

Usage: python scripts/gen_locale_rc.py
Output: notepad4/build/generated/Notepad4.zh-Hans.rc
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "notepad4", "locale", "zh-Hans", "Notepad4.rc")
OUT_DIR = os.path.join(ROOT, "notepad4", "build", "generated")
OUT = os.path.join(OUT_DIR, "Notepad4.zh-Hans.rc")

START_MARK = "// Chinese (Simplified, PRC) resources"
END_MARK = "#endif    // Chinese (Simplified, PRC)"

# Resources already present in the main script (same IDs, different language
# would create duplicate binary resources in the executable).
DROP_TYPES = ("BITMAP", "ICON", "RT_MANIFEST", "DESIGNINFO")


def main():
    if not os.path.isfile(SRC):
        sys.exit("locale script not found: %s" % SRC)

    lines = io.open(SRC, encoding="utf-8").read().replace("\r\n", "\n").split("\n")

    start = next((i for i, line in enumerate(lines) if START_MARK in line), None)
    end = next((i for i, line in enumerate(lines) if END_MARK in line), None)
    if start is None or end is None or end <= start:
        sys.exit("cannot locate the Simplified Chinese block in %s" % SRC)

    kept = []
    dropped = 0
    in_designer = False
    for line in lines[start:end + 1]:
        stripped = line.strip()

        # Drop the Visual Studio designer section (TEXTINCLUDE resources would
        # collide with the ones already defined in the main script).
        if stripped.startswith("#ifdef APSTUDIO_INVOKED"):
            in_designer = True
            continue
        if in_designer:
            if stripped.startswith("#endif") and "APSTUDIO_INVOKED" in stripped:
                in_designer = False
            continue

        tokens = stripped.split()
        # Resource definition lines look like:  IDB_FOO  BITMAP  "path"
        if len(tokens) >= 2 and tokens[1].upper() in DROP_TYPES:
            dropped += 1
            continue
        kept.append(line)

    while kept and not kept[-1].strip():
        kept.pop()

    body = "\n".join(kept) + "\n"
    # The block is included at the end of Notepad4.rc, so no header is needed.
    header = (
        "// Generated by scripts/gen_locale_rc.py -- do not edit by hand.\n"
        "// Source: notepad4/locale/zh-Hans/Notepad4.rc (upstream localization).\n"
        "// Binary resources (icons/bitmaps/manifest) are intentionally omitted.\n\n"
        "// Lexer display names use NP2LEX_* macros from these headers.\n"
        '#include "../../src/EditLexer.h"\n'
        '#include "../../src/EditLexers/EditStyle.h"\n\n'
    )

    os.makedirs(OUT_DIR, exist_ok=True)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header + body)

    print("generated %s (%d lines, %d binary resources dropped)"
          % (OUT, body.count("\n"), dropped))


if __name__ == "__main__":
    main()
